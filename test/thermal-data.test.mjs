import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { dataURL, parseGrid, sampleGrid, colorRGB } from '../groan-ui/thermal-data.mjs';
const grid = JSON.parse(await readFile(new URL('../groan-ui/temperature-global.json', import.meta.url)));
assert.equal(grid.values.length, 64800);
assert.equal(grid.values.filter(v => v !== null).length, 43172);
const cell = sampleGrid(grid, 17.975, -74.975);
assert.equal(cell.value, 29.48);
assert.equal(cell.latitude, 17.975);
assert.equal(sampleGrid(grid, 0, 180).value, sampleGrid(grid, 0, -180).value);
assert.throws(() => dataURL('2024-11-21'));
assert.throws(() => dataURL('2099-01-01'));
assert.throws(() => dataURL('2025-02-30'));
assert.match(decodeURIComponent(dataURL('2024-11-22')), /2024-11-22T12:00:00Z/);
const tiny = { table: { columnNames: ['time','latitude','longitude','CRW_SST'], columnUnits: ['UTC','degrees_north','degrees_east','Celsius'], rows: [['2026-11-21T12:00:00Z',1,0,null], ['2026-11-21T12:00:00Z',1,1,20]] } };
assert.equal(parseGrid(tiny).values[0], null);
assert.deepEqual(colorRGB(null), [29,49,62]);
const change = fn => { const p = structuredClone(tiny); fn(p); return p; };
assert.throws(() => parseGrid(change(p => p.table.columnUnits[3] = 'Kelvin')));
assert.throws(() => parseGrid(change(p => p.table.rows[1][3] = -327.68)));
assert.throws(() => parseGrid(change(p => p.table.rows[1][0] = '2026-11-20T12:00:00Z')));
assert.throws(() => parseGrid(tiny, {expectedDate:'2025-11-21'}));
assert.throws(() => parseGrid(change(p => p.table.rows.reverse())));
console.log('PASS: source values, coordinates, date bounds, nulls, units, sentinel values, mixed dates, grid order and dateline wrap.');
